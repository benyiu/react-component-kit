const languageRefreshSubscribers = new Set();

function subscribeLanguageRefresh(listener) {
    if (typeof listener !== 'function') {
        throw new TypeError('Language refresh subscriber must be a function');
    }
    languageRefreshSubscribers.add(listener);
    return function unsubscribeLanguageRefresh() {
        languageRefreshSubscribers.delete(listener);
    };
}

function callGlobalCallback(name) {
    var callback = globalThis && globalThis[name];
    if (typeof callback === 'function') callback();
}

