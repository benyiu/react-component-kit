    // 當前語言：detection (localStorage, navigator) lives at the application
    // boundary now — main.js runs ui/i18n-dom.js's detectLanguage() at boot and
    // hands the result to initLanguage(). The default is the classic fallback.
    var currentLang = 'zh';

    function normalizeLang(lang) {
        return lang === 'en' ? 'en' : 'zh';
    }

    // The boot-time assignment: no side effects, no notification — exactly
    // what the old module-load detection did.
    function initLanguage(lang) {
        currentLang = normalizeLang(lang);
    }

    // The DOM/persistence half of a language change registers here
    // (ui/i18n-dom.js). Core stays portable, and the classic ordering holds:
    // side effects run before subscribers hear about the change.
    var languageEffects = null;
    function setLanguageEffects(effects) {
        languageEffects = typeof effects === 'function' ? effects : null;
    }

    function setLang(lang) {
        currentLang = normalizeLang(lang);
        if (languageEffects) languageEffects(currentLang);
        notifyLanguageRefresh();
    }

    function t(key, vars) {
        var dict = I18N[currentLang] || I18N.zh;
        var s = dict[key];
        if (s === undefined) s = I18N.zh[key];
        if (s === undefined) s = key;
        if (vars) { for (var k in vars) { if (vars.hasOwnProperty(k)) s = s.split('{{' + k + '}}').join(vars[k] == null ? '' : vars[k]); } }
        return s;
    }
    configureEnumTranslation(t);

    // One display-name rule for the whole UI: a single name shown to the user
    // follows the selected UI language, then falls back to the other language.
    // Keep this separate from form widgets, which intentionally show/edit both
    // stored values.
    function fLocalizedName(nameCN, nameEN, fallback) {
        var cn = nameCN == null ? '' : String(nameCN).trim();
        var en = nameEN == null ? '' : String(nameEN).trim();
        var other = fallback == null ? '' : String(fallback).trim();
        return currentLang === 'en' ? (en || cn || other) : (cn || en || other);
    }
    function fIsIndividualClientType(clientType) {
        return clientType === ENUMS.CLIENT_TYPE.INDIVIDUAL || clientType === 'INDIVIDUAL';
    }
    function fLocalizedClientName(client, fallback) {
        if (!client) return fallback || '—';
        var type = client.clientType || client._clientType || client.client_type;
        // Client records, immutable review snapshots and transaction JOIN
        // metadata use different containers for the same semantic values.
        // Normalize all three here so every list follows one display rule.
        var companyCN = client.companyNameCN || client.clientCompanyNameCN || client.company_name_cn || client._clientCompanyNameCN || '';
        var companyEN = client.companyNameEN || client.clientCompanyNameEN || client.company_name_en || client._clientCompanyNameEN || '';
        var personCN = client.directorNameCN || client.directorNameCn || client.director_name_cn || client._clientNameCN || client._clientNameCn || '';
        var personEN = client.directorNameEN || client.directorNameEn || client.director_name_en || client._clientNameEN || client._clientNameEn || '';
        if (fIsIndividualClientType(type)) {
            return fLocalizedName(personCN, personEN, fLocalizedName(companyCN, companyEN, fallback));
        }
        return fLocalizedName(companyCN, companyEN, fLocalizedName(personCN, personEN, fallback));
    }

const i18nCompatibilityApi = {
    t,
    fLocalizedName,
    fIsIndividualClientType,
    fLocalizedClientName,
    setLang,
};

function installI18nCompatibility(target) {
    if (!target || (typeof target !== 'object' && typeof target !== 'function')) {
        throw new TypeError('i18n compatibility requires a global-like target');
    }
    Object.assign(target, i18nCompatibilityApi);
    Object.defineProperty(target, 'currentLang', {
        configurable: true,
        enumerable: true,
        get: function() { return currentLang; },
        set: function(lang) { setLang(lang); },
    });
    return target;
}

